// Fundamental Tipe Data pada Dart

void main() {
  int angka = 10;
  double desimal = 3.14;
  String teks = "Halo, dunia!";
  bool benar = true;
  var otomatis = "Tipe data var otomatis terinferensi saat inisialisasi";

  print('=== Tipe Data pada Dart ===');
  print('int     : $angka');
  print('double  : $desimal');
  print('String  : $teks');
  print('bool    : $benar');
  print('var     : $otomatis');
}
